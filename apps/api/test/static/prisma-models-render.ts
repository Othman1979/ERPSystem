/**
 * Renders `src/common/openapi/prisma-models.ts` from `prisma/schema.prisma`
 * (PLAT-15): one class per Prisma model with the scalar columns, each with the
 * OpenAPI schema of its JSON form after SerializeInterceptor and JSON.stringify:
 *  - BigInt and Decimal are strings, DateTime is a date-time string (also for
 *    `@db.Date` columns, which serialize as midnight UTC), Int is an integer;
 *  - `Type?` is nullable; a Prisma row always has every scalar key, so all are
 *    required;
 *  - enums reference the generated Prisma enum object under its own name;
 *  - relations are left out: a response DTO adds the ones its query includes.
 *
 * Run `pnpm --filter api openapi:models` after changing the schema; the static
 * spec `prisma-models.spec.ts` fails while the file is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

export const API_ROOT = path.resolve(import.meta.dirname, '..', '..');
export const SCHEMA_FILE = path.join(API_ROOT, 'prisma', 'schema.prisma');
export const MODELS_FILE = path.join(API_ROOT, 'src', 'common', 'openapi', 'prisma-models.ts');

interface Field {
  name: string;
  type: string;
  optional: boolean;
  list: boolean;
  doc: string[];
}

interface Model {
  name: string;
  fields: Field[];
}

const SCALARS = new Set(['String', 'BigInt', 'Decimal', 'Int', 'Float', 'Boolean', 'DateTime', 'Json']);

/** Models, their scalar and enum fields, and the enum names, in schema order. */
export function parseSchema(text: string): { models: Model[]; enums: string[] } {
  const models: Model[] = [];
  const enums: string[] = [];
  let current: Model | null = null;
  let doc: string[] = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    const block = /^(model|enum)\s+(\w+)\s*\{$/.exec(line);
    if (block) {
      if (block[1] === 'enum') enums.push(block[2]);
      else models.push((current = { name: block[2], fields: [] }));
      doc = [];
      continue;
    }
    if (line === '}') {
      current = null;
      continue;
    }
    if (!current) continue;
    if (line.startsWith('///')) {
      doc.push(line.slice(3).trim());
      continue;
    }
    const field = /^(\w+)\s+(\w+)(\?|\[\])?(\s|$)/.exec(line);
    if (field && !line.startsWith('@@')) {
      current.fields.push({
        name: field[1],
        type: field[2],
        optional: field[3] === '?',
        list: field[3] === '[]',
        doc,
      });
    }
    doc = [];
  }
  return { models, enums };
}

function propertyOptions(field: Field, enums: Set<string>): string {
  const parts: string[] = [];
  if (enums.has(field.type)) parts.push(`enum: ${field.type}`, `enumName: '${field.type}'`);
  else if (field.type === 'String' || field.type === 'BigInt') parts.push(`type: 'string'`);
  else if (field.type === 'Decimal') parts.push(`type: 'string'`, `format: 'decimal'`);
  else if (field.type === 'DateTime') parts.push(`type: 'string'`, `format: 'date-time'`);
  else if (field.type === 'Int') parts.push(`type: 'integer'`);
  else if (field.type === 'Float') parts.push(`type: 'number'`);
  else if (field.type === 'Boolean') parts.push(`type: 'boolean'`);
  else if (field.type === 'Json') parts.push('oneOf: ANY_JSON');
  if (field.optional) parts.push('nullable: true');
  if (field.doc.length > 0) parts.push(`description: ${JSON.stringify(field.doc.join(' '))}`);
  return parts.length > 0 ? `{ ${parts.join(', ')} }` : '';
}

function tsType(field: Field, enums: Set<string>): string {
  let base: string;
  if (enums.has(field.type)) base = field.type;
  else if (field.type === 'Int' || field.type === 'Float') base = 'number';
  else if (field.type === 'Boolean') base = 'boolean';
  else if (field.type === 'Json') base = 'unknown';
  else base = 'string';
  return field.optional && base !== 'unknown' ? `${base} | null` : base;
}

/** The TypeScript source of `prisma-models.ts`. */
export function renderModels(schemaText: string): string {
  const { models, enums } = parseSchema(schemaText);
  const enumSet = new Set(enums);
  const usedEnums = new Set<string>();
  const classes: string[] = [];
  for (const model of models) {
    const fields = model.fields.filter((f) => !f.list && (SCALARS.has(f.type) || enumSet.has(f.type)));
    const body = fields.map((f) => {
      if (enumSet.has(f.type)) usedEnums.add(f.type);
      const decorator = `  @ApiProperty(${propertyOptions(f, enumSet)})`;
      return `${decorator}\n  ${f.name}!: ${tsType(f, enumSet)};`;
    });
    classes.push(`/** Scalar columns of the Prisma model \`${model.name}\`, as JSON. */\nexport class ${model.name}Row {\n${body.join('\n')}\n}`);
  }
  const enumImport = [...usedEnums].sort();
  return [
    '// Generated by test/static/prisma-models-render.ts from prisma/schema.prisma.',
    '// Do not edit by hand: run `pnpm --filter api openapi:models` (PLAT-15).',
    "import { ApiProperty } from '@nestjs/swagger';",
    `import { ${enumImport.join(', ')} } from '../../generated/prisma/enums.js';`,
    '',
    '/** A Prisma `Json` column: any JSON value. */',
    "const ANY_JSON = [{ type: 'object', additionalProperties: true }, { type: 'array', items: {} }, { type: 'string' }, { type: 'number' }, { type: 'boolean' }];",
    '',
    classes.join('\n\n'),
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  writeFileSync(MODELS_FILE, renderModels(readFileSync(SCHEMA_FILE, 'utf8')));
  console.log(`wrote ${path.relative(API_ROOT, MODELS_FILE)}`);
}
